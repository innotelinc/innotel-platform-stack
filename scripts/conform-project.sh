  printf 'https://innotelinc.github.io/%s/' "$1"
}

license_badge() {
  case "${1:-MIT}" in
    MIT)         printf '[![License: MIT](https://img.shields.io/badge/license-MIT-blue.svg)](LICENSE)' ;;
    AGPL-3.0-or-later) printf '[![License: AGPL-3.0-or-later](https://img.shields.io/badge/license-AGPL--3.0-or-later-brightgreen.svg)](LICENSE)' ;;
    *)           printf '[![License: %s](https://img.shields.io/badge/license-%s-brightgreen.svg)](LICENSE)' "$1" "$1" ;;
  esac
}

# ── attribution guard + hooks (shared verbatim across repos) ──────────────────

write_guard_lib() {
  cat > "$1/.githooks/guard-lib" <<'GUARD_EOF'
#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# guard-lib — shared patterns + helpers for the attribution guard.
# Sourced by .githooks/commit-msg, .githooks/pre-commit, and the CI workflow
# (.github/workflows/attribution-guard.yml), so one copy of the policy lives
# in every repo and every enforcement point uses the exact same rules.
#
# Policy (content only — never inspects author/committer identity):
#   Attribution text must credit nobody but Darnel Hunter <dhunter@innotel.us>.
#   Concretely the guard rejects:
#     1. git-trailer credit lines (Co-Authored-By, Signed-off-by, ...) whose
#        value is not one of Darnel Hunter's known identities, and
#     2. any line that credits an AI assistant / tool in an attribution
#        phrase (co-author trailers, "Generated with/by X", credit lines).
#   Plain product prose that merely names a technology (an "OpenAI-compatible
#   endpoint", "generated by the release pipeline") is NOT attribution and is
#   allowed.
#
# NOTE: keep this file free of literal attribution strings naming a tool or
# person other than Darnel — the guard scans added lines, including its own
# additions, and must never reject itself. Patterns are assembled below from
# the TOOL_TOKEN variable for exactly this reason.
# ═══════════════════════════════════════════════════════════════════════════

# The only person who may ever be credited. If Darnel commits under another
# address someday, extend this list — do not loosen the non-Darnel rules.
ALLOWED_ATTRIBUTIONS=(
  'Darnel Hunter <dhunter@innotel.us>'
  'Darnel Hunter <darnelhunter@gmail.com>'
  'Darnel Hunter <68697450+innotelinc@users.noreply.github.com>'
  # GitHub's own dependency bot — its automated commits carry a Signed-off-by.
  'dependabot[bot] <support@github.com>'
)

# Git-trailer credit prefixes (case-insensitive, ERE as used by grep -E).
# A line beginning with one of these is an attribution and must name Darnel.
TRAILER_PREFIXES='co-authored-by|signed-off-by|authored-by|helped-by|co-developed-by|based-on-patch-by|reviewed-by|tested-by|reported-by'

# AI assistant/tool tokens. Each token appears ONLY inside an attribution
# phrase below — never as a bare word — so product docs that mention a
# technology (e.g. an OpenAI-compatible endpoint) never trip the guard.
TOOL_TOKEN='codebuff|claude|anthropic|copilot|chatgpt|openai|gemini|bard|aider|cursor|windsurf'

# Attribution phrases naming an AI assistant/tool. Matching is substring-wide
# (grep -E scans the whole line), so emoji either side of the phrase is caught
# by the same pattern. Case-insensitive. The tool tokens are interpolated at
# runtime so the source text stays self-clean.
FORBIDDEN_PATTERNS=(
  "co-authored-by:[[:space:]]*[^<]*(${TOOL_TOKEN})"
  "co-authored-by:[[:space:]]*[^<]*([0-9a-z]\\\\.)?ai[[:space:]<,]"
  "(generated|created|authored|written|built|developed|made|powered|maintained)[[:space:]]+[bw]y[[:space:]]+[^.,;]*(${TOOL_TOKEN})"
  "(generated|created|authored|written|built|developed|made|powered)[[:space:]]+with[[:space:]]+[^.,;]*(${TOOL_TOKEN})"
  "(generated|created|authored|written|built|developed|made|powered)[[:space:]]+(using|via)[[:space:]]+[^.,;]*(${TOOL_TOKEN})"
  "co-authored-by:[[:space:]]*[^<]*noreply@(${TOOL_TOKEN%|*}|codebuff)(\\\\.ai|\\\\.com|\\\\.org)"
  "(${TOOL_TOKEN})[[:space:]]+<noreply@"
  "(credit|credits|thanks|acknowledg)[[:space:]]*:?[[:space:]]*(to[[:space:]]+)?(${TOOL_TOKEN})"
)

# Scan text on stdin; exit 0 if clean, 1 (printing a reason) if any
# attribution is found. Reads stdin ONCE into a variable first — each grep in
# FORBIDDEN_PATTERNS runs against that single in-memory copy.
guard_check_stream() {
  local input
  input="$(cat)"

  # 1. Git-trailer credit lines must name an allowed attribution.
  if printf '%s\n' "$input" | grep -Eiq "^(${TRAILER_PREFIXES})[[:space:]]*:"; then
    local bad
    bad="$(printf '%s\n' "$input" | grep -Eia "^(${TRAILER_PREFIXES})[[:space:]]*:[[:space:]]*[^${ALLOWED_ATTRIBUTIONS[0]}]" || true)"
    if [ -n "$bad" ]; then
      printf '%s\n' "$bad" | sed 's/^/guard: bad trailer:/' >&2
      return 1
    fi
  fi

  # 2. AI-assistant attribution phrases are forbidden.
  for pattern in "${FORBIDDEN_PATTERNS[@]}"; do
    if printf '%s\n' "$input" | grep -Eiq -- "$pattern"; then
      printf 'guard: forbidden attribution pattern matched: %s\n' "$pattern" >&2
      return 1
    fi
  done

  return 0
}
GUARD_EOF
}

write_commit_msg_hook() {
  cat > "$1/.githooks/commit-msg" <<'COMMIT_MSG_EOF'
#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# commit-msg — block attribution in the commit MESSAGE.
#
# Runs with the message file as $1 (the authoritative, final message including
# any trailers a tool appended). Catches credit trailers and "Generated by …"
# lines before the commit is written. Policy: only Darnel Hunter
# <dhunter@innotel.us> may ever be credited. Pairs with the pre-commit hook,
# which guards the committed files themselves.
#
# Install (enables the guard locally):
#     git config core.hooksPath .githooks
# setup.sh on a fresh install already does this.
# ═══════════════════════════════════════════════════════════
set -uo pipefail

MSG_FILE="${1:-}"
HOOK_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=.githooks/guard-lib
# shellcheck disable=SC1091
source "$HOOK_DIR/guard-lib"

say() { printf 'guard: %s\n' "$*"; }

if [ -z "$MSG_FILE" ] || [ ! -f "$MSG_FILE" ]; then
  say "warning: no commit message file given — skipping message guard"
  exit 0
fi

if ! guard_check_stream < "$MSG_FILE"; then
  say "commit blocked: the message contains attribution to someone other than Darnel Hunter <dhunter@innotel.us>."
  exit 1
fi
exit 0
COMMIT_MSG_EOF
}

write_pre_commit_hook() {
  cat > "$1/.githooks/pre-commit" <<'PRE_COMMIT_EOF'
#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# pre-commit — block attribution from landing in committed FILES.
#
# The message/trailer is enforced by the sibling commit-msg hook (the message
# isn't written until later); this hook scans the staged diff so any
# attribution added to docs, READMEs, credits, or comments in the tree itself
# is rejected before the commit can be created. Policy: only Darnel Hunter
# <dhunter@innotel.us> may ever be credited.
#
# Install (enables the guard locally):
#     git config core.hooksPath .githooks
# setup.sh on a fresh install already does this.
# ═══════════════════════════════════════════════════════════
set -uo pipefail

HOOK_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=.githooks/guard-lib
# shellcheck disable=SC1091
source "$HOOK_DIR/guard-lib"

say() { printf 'guard: %s\n' "$*"; }

# Scan only the ADDED lines of the staged diff (never the unchanged context).
added="$(git diff --cached --no-color -U0 2>/dev/null | grep '^+' | grep -v '^+++' || true)"
if [ -n "$added" ]; then
  if ! printf '%s\n' "$added" | guard_check_stream; then
    say "commit blocked: the staged changes introduce attribution to someone other than Darnel Hunter <dhunter@innotel.us>."
    exit 1
  fi
fi
exit 0
PRE_COMMIT_EOF
}

write_attribution_guard_ci() {
  cat > "$1/.github/workflows/attribution-guard.yml" <<'AG_EOF'
# ═══════════════════════════════════════════════════════════════════════════
# attribution-guard.yml — enforce the attribution policy on every push and PR.
#
# Policy: no credit is given to anyone but Darnel Hunter <dhunter@innotel.us>.
# The guard rejects attribution text (Co-Authored-By/Signed-off-by trailers
# naming anyone else, "Generated with/by <AI tool>", credit lines) in:
#   - commit messages introduced by this push/PR,
#   - the PR title/body (pull requests),
#   - lines added to any file in the push/PR.
#
# The actual patterns live in .githooks/guard-lib (shared with the local
# commit-msg/pre-commit hooks), so this workflow just sources that file and
# feeds it the streams above. It never inspects author/committer identity.
# ═══════════════════════════════════════════════════════════════════════════

name: Attribution guard

on:
  push:
  pull_request:
    types: [opened, synchronize, reopened, edited]

permissions:
  contents: read

jobs:
  guard:
    name: Check attribution
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - name: Check commit messages, PR text, and file changes
        env:
          BASE_SHA: ${{ github.event.before }}
          HEAD_SHA: ${{ github.sha }}
          PR_BASE: ${{ github.event.pull_request.base.sha }}
          PR_HEAD: ${{ github.event.pull_request.head.sha }}
          PR_TITLE: ${{ github.event.pull_request.title }}
          PR_BODY: ${{ github.event.pull_request.body }}
          REF_TYPE: ${{ github.ref_type }}
        run: |
          set -uo pipefail
          source .githooks/guard-lib

          fail=0

          # ── Tag pushes introduce no new history ───────────────────────
          # A tag push carries an all-zero "before" SHA (like a brand-new
          # repo), but the tag itself adds only the tagged commit. Scan the
          # tag's own commit message + diff instead of the full history, so
          # historical trailers never block a release.
          if [ "${REF_TYPE:-}" = "tag" ]; then
            git log -1 --format=%B "${GITHUB_REF_NAME}" | guard_check_stream || fail=1
            added="$(git show --format= --no-color -U0 "${GITHUB_REF_NAME}" -- . 2>/dev/null | grep '^+' | grep -v '^+++' || true)"
            if [ -n "$added" ]; then
              printf '%s\n' "$added" | guard_check_stream || fail=1
            fi
            if [ "$fail" -ne 0 ]; then
              echo "::error::Attribution guard failed — only Darnel Hunter <dhunter@innotel.us> may be credited."
              exit 1
            fi
            echo "attribution guard: clean"
            exit 0
          fi

          # ── Determine the commit range to scan ─────────────────────────
          if [ "${GITHUB_EVENT_NAME:-}" = "pull_request" ]; then
            base="${PR_BASE:-}"; head="${PR_HEAD:-}"
          else
            base="${BASE_SHA:-}"; head="${HEAD_SHA:-}"
          fi
          # A brand-new branch/repo pushes with an all-zero "before" SHA —
          # in that case scan the full reachable history instead.
          if [ -n "$base" ] && printf '%s' "$base" | grep -Eq '^0+$'; then
            base=""
          fi

          # ── 1. Commit messages in the range ───────────────────────────
          if [ -n "$base" ] && [ -n "$head" ]; then
            git log --format=%B "${base}..${head}" | guard_check_stream || fail=1
          else
            git log --format=%B | guard_check_stream || fail=1
          fi

          # ── 2. PR title + body (content check only) ───────────────────
          if [ "${GITHUB_EVENT_NAME:-}" = "pull_request" ]; then
            { printf '%s\n' "${PR_TITLE:-}"; printf '%s\n' "${PR_BODY:-}"; } | guard_check_stream || fail=1
          fi

          # ── 3. Lines added to files in the push/PR ────────────────────
          added=""
          if [ -n "$base" ] && [ -n "$head" ]; then
            added="$(git diff --no-color -U0 "$base" "$head" -- . 2>/dev/null | grep '^+' | grep -v '^+++' || true)"
          else
            added="$(git log -p --format= --no-color HEAD 2>/dev/null | grep '^+' | grep -v '^+++' || true)"
          fi
          if [ -n "$added" ]; then
            printf '%s\n' "$added" | guard_check_stream || fail=1
          fi

          if [ "$fail" -ne 0 ]; then
            echo "::error::Attribution guard failed — only Darnel Hunter <dhunter@innotel.us> may be credited."
            exit 1
          fi
          echo "attribution guard: clean"
AG_EOF
}

write_ci_yml() {
  cat > "$1/.github/workflows/ci.yml" <<'CI_EOF'
# ═══════════════════════════════════════════════════════════════════════════
# ci.yml — static checks on push and pull requests.
#
# The repo is maintained at zero findings: structure, compose, hooks, and the
# landing page stay conformant. Attribution guard lives in its own workflow.
# ═══════════════════════════════════════════════════════════════════════════

name: CI

on:
  push:
    branches: [main]
  pull_request:

jobs:
  structure:
    name: Repository structure
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Conformant structure
        run: |
          set -euo pipefail
          for f in README.md LICENSE .env.example web/landing/index.html; do
            if [ ! -f "$f" ]; then
              echo "::error::missing required file: $f"
              exit 1
            fi
          done
          echo "structure: ok"

      - name: .gitignore covers .env
        run: |
          set -euo pipefail
          if ! grep -q '^\.env' .gitignore; then
            echo "::warning:: .gitignore does not list .env"
          fi

  landing:
    name: Landing page sanity
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Landing sanity
        run: |
          set -euo pipefail
          f=web/landing/index.html
          grep -qi '<title>' "$f" || { echo "::error::landing has no <title>"; exit 1; }
          grep -qi 'og:title' "$f" || { echo "::error::landing has no og:title"; exit 1; }
          echo "landing: ok"
CI_EOF
}

write_pages_yml() {
  cat > "$1/.github/workflows/pages.yml" <<'PAGES_EOF'
# Publish the project landing page (web/landing/) to GitHub Pages.
#
#   https://innotelinc.github.io/<repo>/  (landing, static)
#
# Requires Pages to be enabled once: repo Settings -> Pages -> Source:
# "GitHub Actions" (this workflow also attempts to enable it automatically).
# After that, every push to main that touches web/landing republishes.
# workflow_dispatch works too.

name: GitHub Pages

on:
  push:
    # [main, master]: repos default to either branch across the portfolio.
    branches: [main, master]
    paths:
      - "web/landing/**"
      - ".github/workflows/pages.yml"
  workflow_dispatch:

# Cancel any in-flight publish for the same ref; a Pages deploy is atomic.
concurrency:
  group: pages-${{ github.ref }}
  cancel-in-progress: true

permissions:
  contents: read
  pages: write
  id-token: write

jobs:
  deploy:
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: ${{ steps.deployment.outputs.page_url }}
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Configure Pages
        uses: actions/configure-pages@v5
        with:
          enablement: true

      - name: Upload static site
        uses: actions/upload-pages-artifact@v3
        with:
          path: web/landing

      - name: Deploy to GitHub Pages
        id: deployment
        uses: actions/deploy-pages@v4
PAGES_EOF
}

write_makefile() {
  local name="$1" classification="$2"
  cat > "$1/Makefile" <<MAKEFILE_EOF
# ==========================================================================
# ${name} — operator workflow
# Usage: make <target>   (see \`make help\`)
# ==========================================================================

.DEFAULT_GOAL := help
SHELL := /bin/bash

.PHONY: help setup up down logs ps \\
        check:commits check:compose

help: ## Show this help message
\t@echo "${name} — operator workflow"
\t@echo "Usage: make <target>"
\t@grep -E '^[a-zA-Z_:-]+:.*?## .*$$' $(MAKEFILE_LIST) | awk 'BEGIN {FS = ":.*?## "}; {printf "  \\033[36m%-16s\\033[0m %s\\n", $$1, $$2}'

## ---- Bootstrap ------------------------------------------------------------

setup: ## Preflight, install guard hooks, generate .env secrets
\tbash scripts/setup.sh

## ---- Compose (this repo's services) -------------------------------------

up: ## Start all ${name}-managed services
\tdocker compose up -d

down: ## Stop ${name}-managed services (keeps volumes)
\tdocker compose down

logs: ## Tail logs from ${name}-managed services
\tdocker compose logs -f

ps: ## List service status
\tdocker compose ps

## ---- Conformity -----------------------------------------------------------

check:commits: ## Run the attribution guard over recent commit messages
\tbash .githooks/commit-msg .git/COMMIT_EDITMSG 2>/dev/null || true

check:compose: ## Validate the root compose file against .env.example
\tcp .env.example .env
\tdocker compose config --quiet
\trm -f .env
MAKEFILE_EOF
}

