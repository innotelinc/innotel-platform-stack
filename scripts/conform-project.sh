need() { printf 'conform: %s\n' "$*"; }

die() {
  printf 'conform: error: %s\n' "$*" >&2
  exit 1
}

heading() { printf '\n==> %s\n' "$*"; }

github_url() {
  printf 'https://github.com/%s/%s' "$OWNER" "$1"
}

